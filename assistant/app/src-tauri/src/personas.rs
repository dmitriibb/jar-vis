//! Personalities and skills.
//!
//! The source of truth is `<home>/assistant/agents` and `<home>/assistant/skills`.
//! `sync` turns them into opencode project config under `<workspace>/.opencode`,
//! so they apply to Jar-vis sessions only.

use std::collections::BTreeSet;
use std::path::{Path, PathBuf};

use anyhow::{bail, Context, Result};
use serde::Serialize;
use serde_yaml::{Mapping, Value};

use crate::config::Config;

const GENERATED_MARK: &str = "<!-- GENERATED by Jar-vis from assistant/agents/";
const VOICE_RULES_FILE: &str = "_voice-rules.md";
const SCHEDULE_RULES_FILE: &str = "_schedule-rules.md";

/// Fallback when `_voice-rules.md` is missing.
pub const DEFAULT_VOICE_RULES: &str = include_str!("../../../agents/_voice-rules.md");

/// Fallback when `_schedule-rules.md` is missing.
pub const DEFAULT_SCHEDULE_RULES: &str = include_str!("../../../agents/_schedule-rules.md");

/// Files written into an empty home so a fresh install has something to run.
const DEFAULT_FILES: &[(&str, &str)] = &[
    ("assistant/agents/_voice-rules.md", DEFAULT_VOICE_RULES),
    ("assistant/agents/_schedule-rules.md", DEFAULT_SCHEDULE_RULES),
    ("assistant/agents/jarvis.md", include_str!("../../../agents/jarvis.md")),
    ("assistant/agents/pixel.md", include_str!("../../../agents/pixel.md")),
    ("assistant/skills/quick-note/SKILL.md", include_str!("../../../skills/quick-note/SKILL.md")),
    ("assistant/pets/default/pet.json", include_str!("../../../pets/default/pet.json")),
];

const DEFAULT_AGENTS_MD: &str = "# Jar-vis workspace\n\n\
This folder is the Jar-vis workspace. The user talks to you by voice through a small desktop assistant, \
and your answers are read aloud.\n\n\
- Notes the user asks you to save go in `notes/`.\n\
- Other projects live elsewhere on this machine. Ask before working outside this folder.\n";

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct Personality {
    /// File stem, also the opencode agent name.
    pub name: String,
    pub display_name: String,
    pub description: String,
    /// TTS voice id from the model catalog, if the personality sets one.
    pub voice: Option<String>,
    pub speed: Option<f32>,
    pub pet: Option<String>,
}

/// Create the home folder layout and write the bundled defaults that are missing.
pub fn ensure_home(home: &Path) -> Result<()> {
    let fresh = !home.join("assistant").join("agents").is_dir();
    for dir in ["assistant/agents", "assistant/skills", "assistant/pets", "sessions", "models/stt", "models/tts"] {
        std::fs::create_dir_all(home.join(dir)).with_context(|| format!("create {dir} in {}", home.display()))?;
    }
    if fresh {
        for (rel, content) in DEFAULT_FILES {
            let path = home.join(rel);
            if let Some(parent) = path.parent() {
                std::fs::create_dir_all(parent)?;
            }
            if !path.exists() {
                std::fs::write(&path, content).with_context(|| format!("write {}", path.display()))?;
            }
        }
    }
    Ok(())
}

/// Split a markdown file into its YAML frontmatter and body.
pub fn split_frontmatter(text: &str) -> (Option<&str>, &str) {
    let text = text.strip_prefix('\u{feff}').unwrap_or(text);
    let Some(rest) = text.strip_prefix("---") else { return (None, text) };
    let Some(rest) = rest.strip_prefix("\r\n").or_else(|| rest.strip_prefix('\n')) else { return (None, text) };
    let mut offset = 0;
    for line in rest.split_inclusive('\n') {
        if line.trim_end() == "---" {
            return (Some(&rest[..offset]), &rest[offset + line.len()..]);
        }
        offset += line.len();
    }
    (None, text)
}

fn parse_frontmatter(front: Option<&str>) -> Result<Mapping> {
    match front {
        None => Ok(Mapping::new()),
        Some(f) if f.trim().is_empty() => Ok(Mapping::new()),
        Some(f) => match serde_yaml::from_str::<Value>(f).context("invalid frontmatter")? {
            Value::Mapping(m) => Ok(m),
            Value::Null => Ok(Mapping::new()),
            _ => bail!("frontmatter must be a mapping"),
        },
    }
}

pub fn voice_rules(config: &Config) -> String {
    std::fs::read_to_string(config.agents_dir().join(VOICE_RULES_FILE))
        .ok()
        .filter(|t| !t.trim().is_empty())
        .unwrap_or_else(|| DEFAULT_VOICE_RULES.to_string())
}

pub fn schedule_rules(config: &Config) -> String {
    std::fs::read_to_string(config.agents_dir().join(SCHEDULE_RULES_FILE))
        .ok()
        .filter(|t| !t.trim().is_empty())
        .unwrap_or_else(|| DEFAULT_SCHEDULE_RULES.to_string())
}

/// Everything appended to a personality's prompt.
pub fn agent_rules(config: &Config) -> String {
    format!("{}\n\n{}", voice_rules(config).trim(), schedule_rules(config).trim())
}

/// The note put in front of each message to an attached session, whose own
/// agent does not carry the Jar-vis rules. It ends with a blank line.
pub fn attach_prefix(config: &Config) -> String {
    let voice = voice_rules(config)
        .lines()
        .map(str::trim)
        .filter(|l| !l.is_empty() && !l.starts_with('#'))
        .collect::<Vec<_>>()
        .join(" ");
    // The scheduling rules keep their line breaks: the fenced block needs them.
    format!("[voice mode: {voice}\n\n{}\n]\n\n", schedule_rules(config).trim())
}

fn personality_from(name: &str, front: &Mapping) -> Personality {
    let meta = front.get("jarvis").and_then(Value::as_mapping);
    let text = |m: Option<&Mapping>, key: &str| {
        m.and_then(|m| m.get(key)).and_then(Value::as_str).map(str::to_string).filter(|s| !s.trim().is_empty())
    };
    Personality {
        name: name.to_string(),
        display_name: text(meta, "display_name").unwrap_or_else(|| name.to_string()),
        description: text(Some(front), "description").unwrap_or_default(),
        voice: text(meta, "voice"),
        speed: meta.and_then(|m| m.get("speed")).and_then(Value::as_f64).map(|s| s as f32),
        pet: text(meta, "pet"),
    }
}

/// The agent file opencode reads: frontmatter without the `jarvis:` block, a
/// generated-file marker after the frontmatter, the body, then the voice rules.
pub fn render_agent(name: &str, source: &str, voice_rules: &str) -> Result<(Personality, String)> {
    let (front, body) = split_frontmatter(source);
    let mut front = parse_frontmatter(front)?;
    let personality = personality_from(name, &front);
    front.remove("jarvis");
    let yaml = if front.is_empty() { String::new() } else { serde_yaml::to_string(&front)? };
    let out = format!(
        "---\n{yaml}---\n{GENERATED_MARK}{name}.md — edit the source -->\n\n{}\n\n{}\n",
        body.trim(),
        voice_rules.trim()
    );
    Ok((personality, out))
}

fn agent_sources(agents_dir: &Path) -> Vec<(String, PathBuf)> {
    let mut out = Vec::new();
    if let Ok(entries) = std::fs::read_dir(agents_dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            let Some(stem) = path.file_stem().map(|s| s.to_string_lossy().into_owned()) else { continue };
            if path.extension().is_some_and(|e| e == "md") && !stem.starts_with('_') && path.is_file() {
                out.push((stem, path));
            }
        }
    }
    out.sort();
    out
}

pub fn list(config: &Config) -> Vec<Personality> {
    agent_sources(&config.agents_dir())
        .into_iter()
        .filter_map(|(name, path)| {
            let text = std::fs::read_to_string(&path).ok()?;
            let front = parse_frontmatter(split_frontmatter(&text).0).ok()?;
            Some(personality_from(&name, &front))
        })
        .collect()
}

pub fn find(config: &Config, name: &str) -> Option<Personality> {
    list(config).into_iter().find(|p| p.name == name)
}

#[derive(Debug, Default)]
pub struct SyncReport {
    /// True when any generated file was written or removed.
    pub changed: bool,
    pub agents: Vec<String>,
    pub skills: Vec<String>,
    pub warnings: Vec<String>,
}

fn write_if_changed(path: &Path, content: &[u8]) -> Result<bool> {
    if std::fs::read(path).is_ok_and(|old| old == content) {
        return Ok(false);
    }
    if let Some(parent) = path.parent() {
        std::fs::create_dir_all(parent)?;
    }
    std::fs::write(path, content).with_context(|| format!("write {}", path.display()))?;
    Ok(true)
}

fn files_under(root: &Path) -> Vec<PathBuf> {
    let mut out = Vec::new();
    let mut stack = vec![root.to_path_buf()];
    while let Some(dir) = stack.pop() {
        let Ok(entries) = std::fs::read_dir(&dir) else { continue };
        for entry in entries.flatten() {
            let path = entry.path();
            if path.is_dir() {
                stack.push(path);
            } else if let Ok(rel) = path.strip_prefix(root) {
                out.push(rel.to_path_buf());
            }
        }
    }
    out
}

fn remove_empty_dirs(root: &Path) {
    let Ok(entries) = std::fs::read_dir(root) else { return };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            remove_empty_dirs(&path);
            let _ = std::fs::remove_dir(&path);
        }
    }
}

/// Generate `<workspace>/.opencode/{agents,skills}` and `<workspace>/AGENTS.md`.
pub fn sync(config: &Config) -> Result<SyncReport> {
    let workspace = config.workspace_dir();
    let out_agents = workspace.join(".opencode").join("agents");
    let out_skills = workspace.join(".opencode").join("skills");
    std::fs::create_dir_all(&out_agents).with_context(|| format!("create {}", out_agents.display()))?;
    std::fs::create_dir_all(&out_skills)?;
    let mut report = SyncReport::default();
    let rules = agent_rules(config);

    // Agents.
    for (name, path) in agent_sources(&config.agents_dir()) {
        let rendered = std::fs::read_to_string(&path)
            .with_context(|| format!("read {}", path.display()))
            .and_then(|text| render_agent(&name, &text, &rules));
        match rendered {
            Ok((_, content)) => {
                report.changed |= write_if_changed(&out_agents.join(format!("{name}.md")), content.as_bytes())?;
                report.agents.push(name);
            }
            Err(e) => report.warnings.push(format!("agent {name}: {e:#}")),
        }
    }
    // Remove generated agents whose source is gone. Files without the marker are left alone.
    if let Ok(entries) = std::fs::read_dir(&out_agents) {
        for entry in entries.flatten() {
            let path = entry.path();
            let stem = path.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default();
            let generated = std::fs::read_to_string(&path).is_ok_and(|t| t.contains(GENERATED_MARK));
            if generated && !report.agents.contains(&stem) {
                std::fs::remove_file(&path)?;
                report.changed = true;
            }
        }
    }

    // Skills: mirror by copying, since Windows symlinks need Developer Mode.
    let src_skills = config.skills_dir();
    let wanted: BTreeSet<PathBuf> = files_under(&src_skills).into_iter().collect();
    for rel in &wanted {
        let content = std::fs::read(src_skills.join(rel))?;
        report.changed |= write_if_changed(&out_skills.join(rel), &content)?;
    }
    for rel in files_under(&out_skills) {
        if !wanted.contains(&rel) {
            std::fs::remove_file(out_skills.join(&rel))?;
            report.changed = true;
        }
    }
    remove_empty_dirs(&out_skills);
    report.skills = wanted
        .iter()
        .filter(|rel| rel.file_name().is_some_and(|n| n == "SKILL.md"))
        .filter_map(|rel| rel.parent().and_then(Path::file_name).map(|n| n.to_string_lossy().into_owned()))
        .collect();

    // AGENTS.md is written once and then belongs to the user.
    let agents_md = workspace.join("AGENTS.md");
    if !agents_md.exists() {
        std::fs::write(&agents_md, DEFAULT_AGENTS_MD)?;
        report.changed = true;
    }
    Ok(report)
}

#[cfg(test)]
mod tests {
    use super::*;

    const SOURCE: &str = "---\ndescription: Test persona\nmode: primary\npermission:\n  edit: ask\n  bash:\n    \"*\": ask\n    \"ls *\": allow\njarvis:\n  display_name: Testy\n  voice: piper-en_GB-alan-medium\n  speed: 1.1\n  pet: default\n---\nYou are Testy.\n";

    #[test]
    fn frontmatter_split() {
        let (front, body) = split_frontmatter("---\na: 1\n---\nbody\n");
        assert_eq!(front, Some("a: 1\n"));
        assert_eq!(body, "body\n");
        assert_eq!(split_frontmatter("no frontmatter"), (None, "no frontmatter"));
        assert_eq!(split_frontmatter("---\nunterminated"), (None, "---\nunterminated"));
        let (front, body) = split_frontmatter("---\r\na: 1\r\n---\r\nbody");
        assert_eq!(front, Some("a: 1\r\n"));
        assert_eq!(body, "body");
    }

    #[test]
    fn render_strips_jarvis_block_and_appends_rules() {
        let (p, out) = render_agent("testy", SOURCE, "## Voice rules\nBe brief.").unwrap();
        assert_eq!(p.display_name, "Testy");
        assert_eq!(p.voice.as_deref(), Some("piper-en_GB-alan-medium"));
        assert_eq!(p.speed, Some(1.1));
        assert_eq!(p.description, "Test persona");

        let (front, body) = split_frontmatter(&out);
        let front: Mapping = serde_yaml::from_str(front.unwrap()).unwrap();
        assert!(front.get("jarvis").is_none());
        assert_eq!(front.get("mode").and_then(Value::as_str), Some("primary"));
        let bash = front.get("permission").unwrap().get("bash").unwrap();
        assert_eq!(bash.get("ls *").and_then(Value::as_str), Some("allow"));
        // The marker sits after the frontmatter so YAML parsing is unaffected.
        assert!(body.starts_with(GENERATED_MARK));
        assert!(body.contains("You are Testy."));
        assert!(body.trim_end().ends_with("Be brief."));
    }

    #[test]
    fn render_without_frontmatter() {
        let (p, out) = render_agent("plain", "Just a prompt.", "Rules.").unwrap();
        assert_eq!(p.display_name, "plain");
        assert!(out.starts_with("---\n---\n"));
        assert!(out.contains("Just a prompt."));
    }

    #[test]
    fn sync_writes_and_cleans() {
        let root = std::env::temp_dir().join(format!("jarvis-sync-test-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&root);
        let mut config = Config::default();
        config.home = root.to_string_lossy().into_owned();
        ensure_home(&root).unwrap();

        let first = sync(&config).unwrap();
        assert!(first.changed);
        assert_eq!(first.agents, vec!["jarvis", "pixel"]);
        assert_eq!(first.skills, vec!["quick-note"]);
        let ws = config.workspace_dir();
        assert!(ws.join(".opencode/agents/jarvis.md").is_file());
        assert!(!ws.join(".opencode/agents/_voice-rules.md").exists());
        assert!(!ws.join(".opencode/agents/_schedule-rules.md").exists());
        let generated = std::fs::read_to_string(ws.join(".opencode/agents/jarvis.md")).unwrap();
        assert!(generated.contains("## Voice rules") && generated.contains("jarvis-schedule"));
        // The attach note is undone by the same code that shows history.
        let wire = format!("{}hello there", attach_prefix(&config));
        assert_eq!(crate::schedule::display_text(&wire), ("hello there".to_string(), false));
        assert!(ws.join(".opencode/skills/quick-note/SKILL.md").is_file());
        assert!(ws.join("AGENTS.md").is_file());

        // A second run changes nothing.
        assert!(!sync(&config).unwrap().changed);

        // Removing sources removes the generated copies, but not hand-written files.
        std::fs::remove_file(config.agents_dir().join("pixel.md")).unwrap();
        std::fs::remove_dir_all(config.skills_dir().join("quick-note")).unwrap();
        std::fs::write(ws.join(".opencode/agents/mine.md"), "hand written").unwrap();
        let third = sync(&config).unwrap();
        assert!(third.changed);
        assert!(!ws.join(".opencode/agents/pixel.md").exists());
        assert!(ws.join(".opencode/agents/mine.md").is_file());
        assert!(!ws.join(".opencode/skills/quick-note").exists());

        assert_eq!(list(&config).len(), 1);
        let _ = std::fs::remove_dir_all(&root);
    }
}
